ROOT = rcr.ROOT
P256_N = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551


def c_array(name, data):
    body = ', '.join(f'0x{b:02x}' for b in data) or '0'
    return f'static const uint8_t {name}[{max(len(data), 1)}] = {{{body}}};\n'


def make_vectors(path, seed=7):
    from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
    from cryptography.hazmat.primitives.ciphers.aead import AESCCM
    from cryptography.hazmat.primitives.cmac import CMAC
    from cryptography.hazmat.primitives.asymmetric import ec

    rnd = random.Random(seed)
    rb = lambda n: bytes(rnd.getrandbits(8) for _ in range(n))  # noqa: E731
    out = ['/* generated by run_bt_crypto.py */\n#include <stdint.h>\n\n']

    # ECB in the ST byte order: key, input and output reversed
    n_ecb = 6
    out.append(f'#define BT_NUM_ECB {n_ecb}\n')
    keys, ins, outs = [], [], []
    for i in range(n_ecb):
        k, x = rb(16), rb(16)
        y = Cipher(algorithms.AES(k), modes.ECB()).encryptor().update(x)
        keys.append(k[::-1])
        ins.append(x[::-1])
        outs.append(y[::-1])
    for nm, arr in (('g_EcbKey', keys), ('g_EcbIn', ins), ('g_EcbOut', outs)):
        out.append(f'static const uint8_t {nm}[{n_ecb}][16] = {{\n')
        out.append(',\n'.join('\t{' + ', '.join(f'0x{b:02x}' for b in v) + '}' for v in arr))
        out.append('\n};\n')

    # CMAC, standard byte order
    lens = [0, 1, 15, 16, 17, 40, 64, 100, 251]
    out.append('\ntypedef struct { const uint8_t *Key; const uint8_t *Msg; uint32_t Len; const uint8_t *Tag; } BtCmacCase_t;\n')
    out.append(f'#define BT_NUM_CMAC {len(lens)}\n')
    rows = []
    for i, ln in enumerate(lens):
        k, m = rb(16), rb(ln)
        c = CMAC(algorithms.AES(k))
        c.update(m)
        tag = c.finalize()
        out.append(c_array(f'cm_k{i}', k) + c_array(f'cm_m{i}', m) + c_array(f'cm_t{i}', tag))
        rows.append(f'\t{{cm_k{i}, cm_m{i}, {ln}, cm_t{i}}}')
    out.append('static const BtCmacCase_t g_CmacCase[BT_NUM_CMAC] = {\n' + ',\n'.join(rows) + '\n};\n')

    # CCM as the link layer uses it: 13 byte nonce, 4 byte tag, key reversed
    out.append('\ntypedef struct { const uint8_t *Key; const uint8_t *Nonce; const uint8_t *Add; uint16_t AddLen;'
               ' const uint8_t *Pt; const uint8_t *Ct; uint16_t Len; const uint8_t *Tag; uint8_t TagLen; } BtCcmCase_t;\n')
    cases = [(0, 0), (1, 1), (1, 15), (1, 16), (2, 27), (0, 100), (1, 251)]
    out.append(f'#define BT_NUM_CCM {len(cases)}\n')
    rows = []
    for i, (al, pl) in enumerate(cases):
        k, nonce, add, pt = rb(16), rb(13), rb(al), rb(pl)
        tl = 4 if i % 3 else 8
        ct_tag = AESCCM(k, tag_length=tl).encrypt(nonce, pt, add)
        ct, tag = ct_tag[:pl], ct_tag[pl:]
        out.append(c_array(f'cc_k{i}', k[::-1]) + c_array(f'cc_n{i}', nonce) + c_array(f'cc_a{i}', add) +
                   c_array(f'cc_p{i}', pt) + c_array(f'cc_c{i}', ct) + c_array(f'cc_t{i}', tag))
        rows.append(f'\t{{cc_k{i}, cc_n{i}, cc_a{i}, {al}, cc_p{i}, cc_c{i}, {pl}, cc_t{i}, {tl}}}')
    out.append('static const BtCcmCase_t g_CcmCase[BT_NUM_CCM] = {\n' + ',\n'.join(rows) + '\n};\n')

    # P-256, numbers little endian as the stack passes them
    def le(v, n=32):
        return v.to_bytes(n, 'little')

    def keypair():
        while True:
            d = int.from_bytes(rb(32), 'big')
            if 1 <= d < P256_N:
                return d, ec.derive_private_key(d, ec.SECP256R1())

    out.append('\ntypedef struct { uint8_t Priv[32]; uint8_t Pub[64]; uint8_t Peer[64]; uint8_t Dh[32]; } BtPkaCase_t;\n')
    n_pka = 4
    out.append(f'#define BT_NUM_PKA {n_pka}\n')
    rows = []
    for i in range(n_pka):
        d, key = keypair()
        d2, key2 = keypair()
        pn = key.public_key().public_numbers()
        qn = key2.public_key().public_numbers()
        dh = key.exchange(ec.ECDH(), key2.public_key())
        fmt = lambda b: '{' + ', '.join(f'0x{x:02x}' for x in b) + '}'  # noqa: E731
        rows.append('\t{' + fmt(le(d)) + ', ' + fmt(le(pn.x) + le(pn.y)) + ', ' + fmt(le(qn.x) + le(qn.y)) +
                    ', ' + fmt(dh[::-1]) + '}')
    out.append('static const BtPkaCase_t g_PkaCase[BT_NUM_PKA] = {\n' + ',\n'.join(rows) + '\n};\n')
    _, key = keypair()
    qn = key.public_key().public_numbers()
    bad = le(qn.x) + le((qn.y + 1) % (2 ** 256))
    out.append(c_array('g_PkaBadPeer', bad))
    Path(path).write_text(''.join(out))


def build(tmp, wpan):
    gen = tmp / 'gen'
    gen.mkdir()
    make_vectors(gen / 'bt_vectors.h')
    stub = tmp / 'stub'
    stub.mkdir()
    (stub / 'pka_ctrl.h').write_text('')

    cpu = ['-mcpu=cortex-m33', '-mthumb', '-mfloat-abi=soft', '-Os', '-DSTM32WBA65xx', '-DIOSONATA_STM32_WBA',
           '-DuECC_ENABLE_VLI_API=1', '-ffunction-sections', '-fdata-sections', '-g']
    inc = [ROOT / 'include', ROOT / 'ARM/include', ROOT / 'ARM/CMSIS/Core/Include', ROOT / 'ARM/ST/include',
           ROOT / 'ARM/ST/STM32WBAxx/include', ROOT / 'ARM/ST/STM32WBAxx/STM32WBA65/include', ROOT / 'micro-ecc',
           gen, stub, wpan / 'ble/stack/include', wpan / 'ble/stack/include/auto', wpan / 'ble', wpan / 'ble/core',
           wpan / 'ble/core/auto',
           wpan / 'link_layer/ll_cmd_lib/inc', wpan / 'link_layer/ll_sys/inc',
           wpan / 'link_layer/ll_cmd_lib/config/ble_basic_plus_20_links']
    inc = ['-I' + str(p) for p in inc]
    cxx = ['arm-none-eabi-g++', *cpu, '-std=gnu++23', '-Wall', '-Werror', '-fno-exceptions', '-fno-rtti', *inc]
    srcs = [
        HERE / 'bt_crypto_fw.cpp',
        ROOT / 'ARM/ST/STM32WBAxx/src/bt_wba_platform.cpp',
        ROOT / 'ARM/ST/STM32WBAxx/src/bt_wba_pka.cpp',
        ROOT / 'ARM/ST/STM32WBAxx/src/crypto_stm32wba.cpp',
        ROOT / 'src/crypto/crypto_aes_modes.cpp',
        ROOT / 'src/crypto/crypto_aes_soft.cpp',
        ROOT / 'src/crypto/crypto_softrng.cpp',
        ROOT / 'src/crypto/crypto_p256.cpp',
        ROOT / 'src/crypto/crypto_uecc.cpp',
        ROOT / 'src/device.cpp',
    ]
    objs = []
    for src in srcs:
        obj = tmp / (src.stem + '.o')
        rc.run([*cxx, '-c', src, '-o', obj])
        objs.append(obj)
    obj = tmp / 'uECC.o'
    rc.run(['arm-none-eabi-gcc', *cpu, '-std=gnu17', *inc, '-c', ROOT / 'micro-ecc/uECC.c', '-o', obj])
    objs.append(obj)
    elf = tmp / 'bt_crypto_fw.elf'
    rc.run(['arm-none-eabi-g++', *cpu, '-nostartfiles', '-Wl,--gc-sections', '-Wl,-T,' + str(HERE / 'crypto_fw.ld'),
            '--specs=nosys.specs', '--specs=nano.specs', *objs, '-o', elf])
    return elf


def make_driver():
    """Run loop that preempts the firmware at a block of the hardware AES."""
    from unicorn import UC_HOOK_CODE
    from unicorn.arm_const import (UC_ARM_REG_R0, UC_ARM_REG_R1, UC_ARM_REG_R2, UC_ARM_REG_R3, UC_ARM_REG_R4,
                                   UC_ARM_REG_R5, UC_ARM_REG_R6, UC_ARM_REG_R7, UC_ARM_REG_R8, UC_ARM_REG_R9,
                                   UC_ARM_REG_R10, UC_ARM_REG_R11, UC_ARM_REG_R12, UC_ARM_REG_SP, UC_ARM_REG_LR)
    regs = [UC_ARM_REG_R0, UC_ARM_REG_R1, UC_ARM_REG_R2, UC_ARM_REG_R3, UC_ARM_REG_R4, UC_ARM_REG_R5,
            UC_ARM_REG_R6, UC_ARM_REG_R7, UC_ARM_REG_R8, UC_ARM_REG_R9, UC_ARM_REG_R10, UC_ARM_REG_R11,
            UC_ARM_REG_R12, UC_ARM_REG_SP, UC_ARM_REG_LR]

    def driver(uc, syms, env, state, pc):
        # Both Cipher and the inherited CMAC/CCM primitive enter WbaAesRun
        # after acquiring the AES engine. Preempt here to test both paths.
        block = [a for n, a in syms.items() if 'WbaAesRun' in n]
        if len(block) != 1:
            raise SystemExit('FAIL the hardware AES block function was not found in the firmware')
        block = block[0] & ~1
        isr = syms['BtFwIsr'] & ~1
        trap = syms['BtFwTrap'] & ~1
        arm_at = syms['BtFwArm'] & ~1
        ctx = {'target': 0, 'count': 0, 'pending': None, 'saved': None, 'resume': None, 'skip': False,
               'preempts': 0}

        def on_arm(uc, addr, size, user):
            ctx['target'] = uc.reg_read(UC_ARM_REG_R0)
            ctx['count'] = 0

        def on_block(uc, addr, size, user):
            if ctx['skip']:
                ctx['skip'] = False
                return
            if ctx['target'] == 0 or ctx['saved'] is not None:
                return
            ctx['count'] += 1
            if ctx['count'] == ctx['target']:
                ctx['saved'] = [uc.reg_read(r) for r in regs]
                ctx['resume'] = addr
                ctx['pending'] = 'isr'
                ctx['target'] = 0
                uc.emu_stop()

        def on_trap(uc, addr, size, user):
            ctx['pending'] = 'ret'
            uc.emu_stop()

        uc.hook_add(UC_HOOK_CODE, on_arm, begin=arm_at, end=arm_at)
        uc.hook_add(UC_HOOK_CODE, on_trap, begin=trap, end=trap)
        uc.hook_add(UC_HOOK_CODE, on_block, begin=block, end=block)

        start = pc
        while True:
            uc.emu_start(start | 1, 0xFFFFFFFF, count=4_000_000_000)
            if state['done']:
                return
            if ctx['pending'] == 'isr':
                # enter the interrupt routine on the stack of the task, return to the trap
                ctx['pending'] = None
                uc.reg_write(UC_ARM_REG_LR, trap | 1)
                start = isr
                ctx['preempts'] += 1
                sym = syms['g_Preempts']
                uc.mem_write(sym, ctx['preempts'].to_bytes(4, 'little'))
                env.stats['preempts'] += 1
            elif ctx['pending'] == 'ret':
                ctx['pending'] = None
                for r, v in zip(regs, ctx['saved']):
                    uc.reg_write(r, v)
                ctx['saved'] = None
                ctx['skip'] = True
                start = ctx['resume']
            else:
                raise SystemExit('FAIL emulator stopped without a reason')

    return driver


def main():
    for tool in ('arm-none-eabi-g++',):
        if not shutil.which(tool):
            print(f'NOT RUN: {tool} not found')
            return
    try:
        import unicorn  # noqa: F401
        import elftools  # noqa: F401
        import cryptography  # noqa: F401
    except ImportError as e:
        print(f'NOT RUN: {e}. pip install unicorn pyelftools cryptography')
        return
    wpan = os.environ.get('CUBE_WPAN')
    if not wpan or not (Path(wpan) / 'ble/stack/include/ble_defs.h').exists():
        print('NOT RUN: set CUBE_WPAN to a clone of stm32-mw-wpan')
        return
    wpan = Path(wpan)

    rcr.model_self_check()
    errors = []
    with tempfile.TemporaryDirectory(prefix='wba-bt-crypto-') as td:
        elf = build(Path(td), wpan)
        result, text, env, left = rcr.run_fw(elf, 1, 128, True, make_driver())
    passed = text.count('[PASS]')
    failed = text.count('[FAIL]')
    total = passed + failed
    print(f'{passed} passed, {failed} failed, result {result}')
    print('  model counters:', dict(sorted(env.stats.items())))
    for line in text.splitlines():
        if '[FAIL]' in line:
            errors.append(line.strip())
    if result != 0:
        errors.append(f'the test returned {result}')
    if 'Bluetooth crypto hooks' not in text:
        errors.append('no test output')
    # HW_RNG_Get of bt_wba_platform.cpp starts the RNG with the setup the HAL
    # uses when the device header has no RNG_CR_NIST_VALUE. The WBA65 header
    # has it, and CryptoWbaRng uses it. The platform RNG is not part of
    # the AES and PKA change, so it is reported and not counted.
    rng_notes = [v for v in env.viol if v.startswith('RNG health test register') or
                 v.startswith('RNG configuration')]
    if rng_notes:
        print(f'  note: platform HW_RNG_Get does not use the NIST RNG setup ({len(rng_notes)} model messages)')
    for v in [v for v in env.viol if v not in rng_notes][:10]:
        errors.append(f'model violation: {v}')
    for m in left:
        errors.append(m)
    if env.stats['aes_blocks'] == 0 or env.stats['pka_mul'] == 0:
        errors.append('the models were not used')
    if env.stats['preempts'] != 3:
        errors.append(f'{env.stats["preempts"]} preemptions, 3 expected')
    if '-v' in sys.argv:
        print(text)
    print(f'STM32WBA Bluetooth crypto hooks on the emulator: {total} checks, {len(errors)} failures')
    for e in errors:
        print('  FAIL', e)
    print('Hardware not tested.')
    if errors:
        sys.exit(1)


if __name__ == '__main__':
    main()
