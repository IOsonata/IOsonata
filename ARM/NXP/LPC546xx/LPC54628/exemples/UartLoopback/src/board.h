#ifndef __BOARD_H__
#define __BOARD_H__

// Flexcomm 0: same pins as the LPCXpresso54628 UartPrbsTxTest example.
// LPC-Link2 VCOM uses P0.29 (RX) and P0.30 (TX), function 1.
// UART data is echoed in both Debug and Release; no console uses this UART.
#define UART_DEVNO			0
#define UART_BAUDRATE		1000000
#define UART_RX_PORT		0
#define UART_RX_PIN			29
#define UART_RX_PINOP		IOPINOP_FUNC1
#define UART_TX_PORT		0
#define UART_TX_PIN			30
#define UART_TX_PINOP		IOPINOP_FUNC1

// Interrupt-driven RX/TX FIFOs. Set UART_DMA_MODE to true for TX DMA, RX
// stays on the RX FIFO interrupt.
#ifndef UART_INT_MODE
#define UART_INT_MODE		true
#endif
#define UART_DMA_MODE		false

#define UART_PINS { \
	{UART_RX_PORT, UART_RX_PIN, UART_RX_PINOP, IOPINDIR_INPUT, IOPINRES_NONE, IOPINTYPE_NORMAL}, \
	{UART_TX_PORT, UART_TX_PIN, UART_TX_PINOP, IOPINDIR_OUTPUT, IOPINRES_NONE, IOPINTYPE_NORMAL}, \
}

#endif
