typedef void (*BtFwHandler_t)(uint32_t EvtId, void *pCtx);

#define BT_FW_QUE_LEN	4

static BtFwHandler_t s_QueHandler[BT_FW_QUE_LEN];
static void *s_QueCtx[BT_FW_QUE_LEN];
static int s_QueCnt;

extern "C" bool BtEvtQue(uint32_t EvtId, void *pCtx, BtFwHandler_t Handler)
{
	(void)EvtId;
	if (s_QueCnt >= BT_FW_QUE_LEN)
	{
		return false;
	}
	s_QueHandler[s_QueCnt] = Handler;
	s_QueCtx[s_QueCnt] = pCtx;
	s_QueCnt++;

	return true;
}

// Run what the platform queued, the way the event task of the application does
static void BtFwPump(void)
{
	while (s_QueCnt > 0)
	{
		BtFwHandler_t h = s_QueHandler[0];
		void *c = s_QueCtx[0];

		for (int i = 1; i < s_QueCnt; i++)
		{
			s_QueHandler[i - 1] = s_QueHandler[i];
			s_QueCtx[i - 1] = s_QueCtx[i];
		}
		s_QueCnt--;
		h(0, c);
	}
}

