static int s_Pass;
static int s_Fail;

static void check(const char *pName, bool bOk)
{
	printf("  [%s] %s\r\n", bOk ? "PASS" : "FAIL", pName);
	if (bOk)
	{
		s_Pass++;
	}
	else
	{
		s_Fail++;
	}
}

// Preemption routine. The emulator calls it at a chosen AES block of a task
// level operation, with the return address at BtFwTrap.
static volatile int s_IsrRuns;
static volatile bool s_IsrOk;

extern "C" void BtFwIsr(void)
{
	uint8_t out[16];

	BAES_EcbCrypt(g_EcbKey[0], g_EcbIn[0], out, 1);
	s_IsrOk = memcmp(out, g_EcbOut[0], 16) == 0;
	s_IsrRuns = s_IsrRuns + 1;
}

// Keeps the routines the emulator enters by address out of the linker's
// garbage collection
extern "C" void (* const g_BtFwEntries[])(void);
void (* const g_BtFwEntries[])(void) = { BtFwIsr, BtFwTrap };

static void EcbVectors(void)
{
	bool ok = true;

	BAES_Reset();
	for (unsigned i = 0; i < BT_NUM_ECB; i++)
	{
		uint8_t out[16];

		BAES_EcbCrypt(g_EcbKey[i], g_EcbIn[i], out, 1);
		ok = ok && memcmp(out, g_EcbOut[i], 16) == 0;
	}
	check("BAES_EcbCrypt, ST byte order", ok);
}

static void CmacVectors(void)
{
	bool ok = true;

	for (unsigned i = 0; i < BT_NUM_CMAC; i++)
	{
		uint8_t tag[16];

		BAES_CmacSetKey(g_CmacCase[i].Key);
		memset(tag, 0xA5, sizeof(tag));
		BAES_CmacCompute(g_CmacCase[i].Msg, g_CmacCase[i].Len, tag);
		ok = ok && memcmp(tag, g_CmacCase[i].Tag, 16) == 0;
	}
	check("BAES_CmacCompute, lengths 0 to 251", ok);

	ok = true;
	for (unsigned i = 0; i < BT_NUM_CMAC; i++)
	{
		const BtCmacCase_t *pC = &g_CmacCase[i];

		for (uint32_t split = 0; split < pC->Len || split == 0; split += 16)
		{
			uint8_t tag[16];

			BAES_CmacSetKey(pC->Key);
			BAES_CmacCompute(pC->Msg, split, nullptr);
			BAES_CmacCompute(pC->Msg + split, pC->Len - split, tag);
			ok = (memcmp(tag, pC->Tag, 16) == 0) && ok;
		}
	}
	check("BAES_CmacCompute, incremental whole-block appends", ok);
}

static bool CcmOne(const BtCcmCase_t *pC)
{
	uint8_t out[300];
	uint8_t tag[16];
	uint8_t back[300];
	uint8_t bad[16];
	bool ok;

	memset(out, 0xA5, sizeof(out));
	memset(tag, 0xA5, sizeof(tag));
	ok = BAES_CcmCrypt(0, pC->Key, 13, pC->Nonce, pC->AddLen, pC->Add,
					   pC->Len, pC->Pt, pC->TagLen, tag, out) == 0;
	ok = ok && memcmp(out, pC->Ct, pC->Len) == 0;
	ok = ok && memcmp(tag, pC->Tag, pC->TagLen) == 0;

	memset(back, 0xA5, sizeof(back));
	memcpy(tag, pC->Tag, pC->TagLen);
	ok = ok && BAES_CcmCrypt(1, pC->Key, 13, pC->Nonce, pC->AddLen, pC->Add,
							 pC->Len, pC->Ct, pC->TagLen, tag, back) == 0;
	ok = ok && memcmp(back, pC->Pt, pC->Len) == 0;

	memcpy(bad, pC->Tag, pC->TagLen);
	bad[0] ^= 1U;
	ok = ok && BAES_CcmCrypt(1, pC->Key, 13, pC->Nonce, pC->AddLen, pC->Add,
							 pC->Len, pC->Ct, pC->TagLen, bad, back) != 0;

	return ok;
}

static void CcmVectors(void)
{
	bool ok = true;

	for (unsigned i = 0; i < BT_NUM_CCM; i++)
	{
		ok = CcmOne(&g_CcmCase[i]) && ok;
	}
	check("BAES_CcmCrypt, seal, open and tag failure", ok);
}

static void Preempted(void)
{
	// Longest CMAC and CCM cases are last in the tables
	const BtCmacCase_t *pM = &g_CmacCase[BT_NUM_CMAC - 1];
	const BtCcmCase_t *pC = &g_CcmCase[BT_NUM_CCM - 1];
	uint8_t tag[16];
	uint8_t out[300];
	int before;

	// CMAC cut at its 3rd block
	s_IsrRuns = 0;
	s_IsrOk = false;
	before = g_Preempts;
	BtFwArm(3);
	BAES_CmacSetKey(pM->Key);
	memset(tag, 0xA5, sizeof(tag));
	BAES_CmacCompute(pM->Msg, pM->Len, tag);
	BtFwArm(0);
	check("CMAC with an interrupt call in the middle, task result",
		  memcmp(tag, pM->Tag, 16) == 0);
	check("CMAC with an interrupt call in the middle, interrupt result",
		  g_Preempts - before == 1 && s_IsrRuns == 1 && s_IsrOk);

	// CCM seal cut at its 5th block
	s_IsrRuns = 0;
	s_IsrOk = false;
	before = g_Preempts;
	BtFwArm(5);
	memset(out, 0xA5, sizeof(out));
	memset(tag, 0xA5, sizeof(tag));
	bool ok = BAES_CcmCrypt(0, pC->Key, 13, pC->Nonce, pC->AddLen, pC->Add,
							pC->Len, pC->Pt, pC->TagLen, tag, out) == 0;
	BtFwArm(0);
	check("CCM seal with an interrupt call in the middle, task result",
		  ok && memcmp(out, pC->Ct, pC->Len) == 0 &&
		  memcmp(tag, pC->Tag, pC->TagLen) == 0);
	check("CCM seal with an interrupt call in the middle, interrupt result",
		  g_Preempts - before == 1 && s_IsrRuns == 1 && s_IsrOk);

	// CCM open cut at its 4th block
	uint8_t back[300];

	s_IsrRuns = 0;
	s_IsrOk = false;
	before = g_Preempts;
	BtFwArm(4);
	memset(back, 0xA5, sizeof(back));
	memcpy(tag, pC->Tag, pC->TagLen);
	ok = BAES_CcmCrypt(1, pC->Key, 13, pC->Nonce, pC->AddLen, pC->Add,
					   pC->Len, pC->Ct, pC->TagLen, tag, back) == 0;
	BtFwArm(0);
	check("CCM open with an interrupt call in the middle, task result",
		  ok && memcmp(back, pC->Pt, pC->Len) == 0);
	check("CCM open with an interrupt call in the middle, interrupt result",
		  g_Preempts - before == 1 && s_IsrRuns == 1 && s_IsrOk);
}

static int PkaWait(void)
{
	s_PkaDone = false;
	BtFwPump();

	return s_PkaDone ? 1 : 0;
}

static void PkaVectors(void)
{
	bool okKey = true;
	bool okDh = true;
	bool okBusy = true;
	bool okEarly = true;

	for (unsigned i = 0; i < BT_NUM_PKA; i++)
	{
		const BtPkaCase_t *pC = &g_PkaCase[i];
		uint32_t priv[8];
		uint32_t peer[16];
		uint32_t pub[16];
		uint32_t dh[8];

		memcpy(priv, pC->Priv, 32);
		PKACTRL_Reset();

		// Public key. Read before the end is refused, a second start is busy.
		memset(pub, 0, sizeof(pub));
		okBusy = okBusy && PKACTRL_StartP256Key(priv) == 0;
		okBusy = okBusy && PKACTRL_StartP256Key(priv) == -2;
		okEarly = okEarly && PKACTRL_ReadP256Key(pub) == -3;
		okKey = okKey && PkaWait() == 1;
		okKey = okKey && PKACTRL_ReadP256Key(pub) == 0;
		okKey = okKey && memcmp(pub, pC->Pub, 64) == 0;

		// Shared secret with a valid peer
		memcpy(peer, pC->Peer, 64);
		memset(dh, 0, sizeof(dh));
		okBusy = okBusy && PKACTRL_StartDhKey(priv, peer) == 0;
		okBusy = okBusy && PKACTRL_StartDhKey(priv, peer) == -2;
		okEarly = okEarly && PKACTRL_ReadDhKey(dh) == -3;
		okDh = okDh && PkaWait() == 1;
		okDh = okDh && PKACTRL_ReadDhKey(dh) == 0;
		okDh = okDh && memcmp(dh, pC->Dh, 32) == 0;
	}
	check("PKACTRL_StartP256Key and ReadP256Key", okKey);
	check("PKACTRL_StartDhKey and ReadDhKey", okDh);
	check("second start while an operation is pending is busy", okBusy);
	check("read before the end of the operation is refused", okEarly);

	// A peer point off the curve: the end is reported, the secret is refused
	{
		uint32_t priv[8];
		uint32_t peer[16];
		uint32_t dh[8];

		memcpy(priv, g_PkaCase[0].Priv, 32);
		memcpy(peer, g_PkaBadPeer, 64);
		memset(dh, 0, sizeof(dh));
		PKACTRL_Reset();
		bool ok = PKACTRL_StartDhKey(priv, peer) == 0;
		ok = ok && PkaWait() == 1;
		ok = ok && PKACTRL_ReadDhKey(dh) == -3;
		bool zero = true;
		for (int i = 0; i < 8; i++)
		{
			zero = zero && dh[i] == 0;
		}
		check("peer point off the curve: operation ends, secret refused", ok);
		check("peer point off the curve: no secret is returned", zero);
	}

	// A private scalar of zero
	{
		uint32_t priv[8] = {};
		uint32_t pub[16];

		PKACTRL_Reset();
		bool ok = PKACTRL_StartP256Key(priv) == 0;
		ok = ok && PkaWait() == 1;
		ok = ok && PKACTRL_ReadP256Key(pub) == -3;
		check("private scalar 0: operation ends, key refused", ok);
	}
}

static void RngCheck(void)
{
	uint32_t a[4] = {};
	uint32_t b[4] = {};

	HW_RNG_Get(4, a);
	HW_RNG_Get(4, b);
	check("HW_RNG_Get gives different non zero words",
		  memcmp(a, b, sizeof(a)) != 0 && (a[0] | a[1] | a[2] | a[3]) != 0);
}

static void RunAll(void)
{
	printf("Bluetooth crypto hooks\r\n");
	EcbVectors();
	CmacVectors();
	CcmVectors();
	Preempted();
	PkaVectors();
	RngCheck();
	printf("\r\n%d passed, %d failed\r\n", s_Pass, s_Fail);
}

extern "C" int main(void)
{
	volatile unsigned idx = 0;
	void (* volatile pEntry)(void) = g_BtFwEntries[idx];

	(void)pEntry;
	RunAll();
	g_CryptoFwResult = s_Fail;
	CryptoFwDone();

	return 0;
}

// Minimal start: stack, data and bss, then main
extern "C" uint32_t _sidata, _sdata, _edata, _sbss, _ebss, _estack;

extern "C" void ResetHandler(void)
{
	uint32_t *src = &_sidata;

	for (uint32_t *dst = &_sdata; dst < &_edata; )
	{
		*dst++ = *src++;
	}
	for (uint32_t *dst = &_sbss; dst < &_ebss; )
	{
		*dst++ = 0;
	}
	main();
	while (1)
	{
	}
}

extern "C" __attribute__((section(".isr_vector"), used))
void (* const __Vectors[16 + 128])(void) = {
	(void (*)(void))&_estack,
	ResetHandler,
};
